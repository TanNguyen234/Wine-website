-- V18: Widen core money columns from DECIMAL(10,2) to DECIMAL(18,2) NOT NULL (lockstep with JPA entities)

IF EXISTS (
    SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS
    WHERE TABLE_SCHEMA = 'dbo' AND TABLE_NAME = 'orders' AND COLUMN_NAME = 'total_price'
      AND (NUMERIC_PRECISION <> 18 OR NUMERIC_SCALE <> 2 OR IS_NULLABLE = 'YES')
)
BEGIN
    ALTER TABLE dbo.orders ALTER COLUMN total_price DECIMAL(18,2) NOT NULL;
END;

